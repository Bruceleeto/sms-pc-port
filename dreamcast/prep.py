#!/usr/bin/env python3
"""Prepare the Dreamcast build: patched decomp sources and the unit lists.

usage: dreamcast/prep.py BUILD_DIR

Does what CMakeLists.txt does at configure time for the PC build:
- applies decomp-patches/*.patch, in name order, to copies of the touched
  files under BUILD_DIR/patched (same paths as in decomp/), rewriting only
  files whose content changed so unchanged objects are not rebuilt;
- lists the game units (as tools/gen_sources.py does) into BUILD_DIR/sources.mk,
  with patched copies standing in for their originals.
"""
import os
import re
import shutil
import subprocess
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..'))
DECOMP = os.path.join(ROOT, 'decomp')
# Source roots (relative to the decomp) and whether their .c files are C++.
ROOTS = (('src', False), ('libs/JSystem/src', True), ('libs/THPPlayer/src', True))


def rel(p):
    return os.path.relpath(p, ROOT).replace(os.sep, '/')


def apply_patches(build):
    patched = os.path.join(build, 'patched')
    scratch = patched + '.new'
    shutil.rmtree(scratch, ignore_errors=True)
    os.makedirs(scratch)
    touched = []
    # the PC port's patches, then the Dreamcast's own (dreamcast/patches)
    patches = []
    for d in ('decomp-patches', 'dreamcast/patches'):
        pdir = os.path.join(ROOT, d)
        if os.path.isdir(pdir):
            patches += [(n, os.path.join(pdir, n)) for n in sorted(os.listdir(pdir))]
    for name, p in patches:
        if not name.endswith('.patch'):
            continue
        with open(p, encoding='utf-8', errors='replace') as fp:
            for line in fp:
                m = re.match(r'^\+\+\+ b/(\S+)', line)
                if m and m.group(1) not in touched:
                    f = m.group(1)
                    os.makedirs(os.path.dirname(os.path.join(scratch, f)), exist_ok=True)
                    shutil.copyfile(os.path.join(DECOMP, f), os.path.join(scratch, f))
                    touched.append(f)
        if subprocess.call(['patch', '-p1', '--quiet', '-d', scratch, '-i', p]) != 0:
            sys.exit('port patch failed to apply: ' + name)

    for d, _, files in os.walk(patched):
        for f in files:
            r = os.path.relpath(os.path.join(d, f), patched).replace(os.sep, '/')
            if r not in touched:
                os.remove(os.path.join(d, f))
    for f in touched:
        src, dst = os.path.join(scratch, f), os.path.join(patched, f)
        new = open(src, 'rb').read()
        if not os.path.exists(dst) or open(dst, 'rb').read() != new:
            os.makedirs(os.path.dirname(dst), exist_ok=True)
            with open(dst, 'wb') as fp:
                fp.write(new)
    shutil.rmtree(scratch)
    return patched, set(touched)


def main():
    build = os.path.abspath(sys.argv[1])
    os.makedirs(build, exist_ok=True)
    patched, touched = apply_patches(build)

    cfg = open(os.path.join(DECOMP, 'configure.py')).read()
    pch = set(re.findall(r'PCHObject\(\s*[^,]+,\s*"([^"]+)"', cfg))

    def path(r):
        return rel(os.path.join(patched if r in touched else DECOMP, r))

    cxx, c, pchs = [], [], []
    for sub, c_is_cxx in ROOTS:
        for d, _, files in os.walk(os.path.join(DECOMP, sub)):
            for f in files:
                if not f.endswith(('.c', '.cpp')):
                    continue
                unit = os.path.relpath(os.path.join(d, f), os.path.join(DECOMP, sub)).replace(os.sep, '/')
                r = sub + '/' + unit
                (c if f.endswith('.c') and not c_is_cxx else cxx).append(path(r))
                if sub == 'src' and unit in pch:
                    pchs.append(path(r))

    def block(name, items):
        return '%s := \\\n%s\n\n' % (name, ' \\\n'.join('\t' + i for i in sorted(items)))

    out = os.path.join(build, 'sources.mk')
    text = '# Generated by dreamcast/prep.py -- do not edit.\n'
    text += block('GAME_CXX', cxx) + block('GAME_C', c) + block('GAME_PCH', pchs)
    text += 'PATCHED := %s\n' % rel(patched)
    if not os.path.exists(out) or open(out).read() != text:
        with open(out, 'w') as fp:
            fp.write(text)
    print('prep: %d patches, %d C++ units, %d C units' % (
        len([n for n in os.listdir(os.path.join(ROOT, 'decomp-patches')) if n.endswith('.patch')]),
        len(cxx), len(c)))


if __name__ == '__main__':
    main()
